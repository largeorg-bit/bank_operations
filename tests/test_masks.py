import pytest

from src.masks import get_mask_account, get_mask_card_number


@pytest.mark.parametrize(
    "номер, ожидаемый_результат",
    [
        (7000792289606362, "7000 79** **** 6362"),
        (7000792289606361, "7000 79** **** 6361"),
        (4111111111111111, "4111 11** **** 1111"),
    ],
)
def test_маскирование_номера_карты(номер, ожидаемый_результат):
    assert get_mask_card_number(номер) == ожидаемый_результат


@pytest.mark.parametrize(
    "номер, ожидаемый_результат",
    [
        (123456789012345, "1234 56** **** 2345"),
        (1234, "1234 ** **** 1234"),
    ],
)
def test_маскирование_карты_короткий_номер(номер, ожидаемый_результат):
    assert get_mask_card_number(номер) == ожидаемый_результат


def test_маскирование_карты_через_фикстуру(номера_карт):
    for номер, ожидаемый_результат in номера_карт:
        assert get_mask_card_number(номер) == ожидаемый_результат


